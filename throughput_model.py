def congestion_factor(environment: str, time_of_day: str, day_of_week: str) -> float:
    """Indicative congestion multiplier (0–1) for scenario. Not site-calibrated."""
    env = (environment or "urban").strip().lower().replace(" ", "")
    if env not in ("city", "urban", "suburban", "rural"):
        env = "urban"
    tod = (time_of_day or "off_peak").strip().lower().replace(" ", "")
    if tod not in ("peak", "off_peak"):
        tod = "off_peak"
    dow = (day_of_week or "weekday").strip().lower()
    if dow not in ("weekday", "weekend"):
        dow = "weekday"
    return CONGESTION_FACTORS.get((env, tod, dow), 0.90)


# Calibration table: effective MCS from (RSRP, RSRQ). Grid: RSRP -75,-95,-105,-124; RSRQ -8,-10,-13,-15,-20,-24.
# Table[rsrp_idx][rsrq_idx] = MCS. RSRP ascending -124..-75, RSRQ ascending -24..-8.
_EFFECTIVE_MCS_RSRP_GRID = (-124.0, -105.0, -95.0, -75.0)
_EFFECTIVE_MCS_RSRQ_GRID = (-24.0, -20.0, -15.0, -13.0, -10.0, -8.0)
_EFFECTIVE_MCS_TABLE = (
    (0, 1, 3, 7, 9, 10),    # RSRP -124
    (0, 3, 7, 10, 13, 15),  # RSRP -105
    (0, 5, 10, 15, 20, 24), # RSRP -95
    (2, 15, 20, 25, 27, 28), # RSRP -75
)


def effective_mcs_from_rsrp_rsrq(rsrp_dbm: float, rsrq_db: float | None) -> int:
    """Effective MCS from RSRP and optional RSRQ using calibration table.
    If RSRQ is None, returns rsrp_to_estimated_mcs(rsrp_dbm). Otherwise bilinear
    interpolation over the (RSRP, RSRQ) grid; result rounded to valid MCS 0–28.
    Effective MCS is never higher than the RSRP-only estimated MCS."""
    if rsrq_db is None:
        return rsrp_to_estimated_mcs(rsrp_dbm)
    try:
        rsrp = float(rsrp_dbm)
        rsrq = float(rsrq_db)
    except (TypeError, ValueError):
        return rsrp_to_estimated_mcs(rsrp_dbm)
    rp = _EFFECTIVE_MCS_RSRP_GRID
    rq = _EFFECTIVE_MCS_RSRQ_GRID
    # Clamp to grid bounds for extrapolation
    rsrp = max(rp[0], min(rp[-1], rsrp))
    rsrq = max(rq[0], min(rq[-1], rsrq))
    # Find cell: i such that rp[i] <= rsrp <= rp[i+1]
    i = 0
    for ii in range(len(rp) - 1):
        if rp[ii] <= rsrp <= rp[ii + 1]:
            i = ii
            break
        i = ii
    if rsrp >= rp[-1]:
        i = len(rp) - 2
    j = 0
    for jj in range(len(rq) - 1):
        if rq[jj] <= rsrq <= rq[jj + 1]:
            j = jj
            break
        j = jj
    if rsrq >= rq[-1]:
        j = len(rq) - 2
    rp0, rp1 = rp[i], rp[i + 1]
    rq0, rq1 = rq[j], rq[j + 1]
    denom_rp = rp1 - rp0
    denom_rq = rq1 - rq0
    s = (rsrp - rp0) / denom_rp if denom_rp else 0.0
    t = (rsrq - rq0) / denom_rq if denom_rq else 0.0
    s = max(0.0, min(1.0, s))
    t = max(0.0, min(1.0, t))
    m00 = _EFFECTIVE_MCS_TABLE[i][j]
    m10 = _EFFECTIVE_MCS_TABLE[i + 1][j]
    m01 = _EFFECTIVE_MCS_TABLE[i][j + 1]
    m11 = _EFFECTIVE_MCS_TABLE[i + 1][j + 1]
    mcs_float = (1 - s) * (1 - t) * m00 + s * (1 - t) * m10 + (1 - s) * t * m01 + s * t * m11
    mcs = _round_to_valid_mcs(mcs_float)
    # Effective MCS can never exceed RSRP-only estimated MCS
    return min(mcs, rsrp_to_estimated_mcs(rsrp_dbm))


def rsrq_to_rsrp_offset_dbm(rsrq_db: float | None, rsrp_dbm: float | None = None) -> float:
    """Legacy: RSRQ → RSRP offset. Prefer effective_mcs_from_rsrp_rsrq() for effective MCS."""
    if rsrq_db is None:
        return 0.0
    try:
        r = float(rsrq_db)
    except (TypeError, ValueError):
        return 0.0
    if r >= -10.0:
        return 0.0
    if r <= -24.0:
        return -12.61
    if r <= -13.0:
        return 10.22 + (r + 13.0) * (-12.61 - 10.22) / (-24.0 + 13.0)
    return 10.22 * (r + 10.0) / (-13.0 + 10.0)


def rsrq_de_rate_factor(rsrq_db: float | None) -> float:
    """De-rate factor (0–1) from average RSRQ (dB). Linear: RSRQ ≥ -10: 1.0; -24: 0.01; linear in between."""
    if rsrq_db is None:
        return 1.0
    try:
        r = float(rsrq_db)
    except (TypeError, ValueError):
        return 1.0
    if r >= -10.0:
        return 1.0
    if r <= -24.0:
        return 0.01
    return 1.0 + (r + 10.0) * (0.01 - 1.0) / (-24.0 + 10.0)
